def ctype(vals):
    ts = set()
    for v in vals:
        if v in ("", "NaN"): ts.add("missing"); continue
        try: int(v); ts.add("int"); continue
        except ValueError: pass
        try: float(v); ts.add("float"); continue
        except ValueError: pass
        ts.add("str")
    ts.discard("missing")
    return "/".join(sorted(ts)) or "empty"

