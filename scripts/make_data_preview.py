def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]

def fmeta(p):
    p = D / p
    st = p.stat()
    return (f"`{p.relative_to(D)}`", f"{st.st_size/1e6:.1f} MB", datetime.date.fromtimestamp(st.st_mtime).isoformat(), sha(p))

